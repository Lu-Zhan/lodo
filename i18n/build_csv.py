def main():
    out = ROOT / "strings.csv"
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["slug", "zh", "en", "scope", "note"])
        import re as _re
        seen_slugs = {}
        for zh, en, scope, note in ROWS:
            base = "".join(c if c.isalnum() else "_" for c in en.lower())
            base = _re.sub(r"_+", "_", base).strip("_")
            if len(base) > 40:
                # 截到最后一个完整单词边界,避免截出半个词(如 _it_u)这种不稳定的
                # case 名——slug 一旦被调用点手写引用,截断点漂移就会破坏调用点。
                cut = base[:40].rfind("_")
                base = base[:cut] if cut > 10 else base[:40]
            base = base.strip("_") or "s"
            slug = f"{scope}.{base}"
            n = seen_slugs.get(slug, 0) + 1
            seen_slugs[slug] = n
            if n > 1:
                slug = f"{slug}_{n}"
            w.writerow([slug, zh, en, scope, note])
    print(f"wrote {len(ROWS)} rows to {out}")

if __name__ == "__main__":
    main()
